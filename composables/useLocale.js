export const useLocale = () => {
  const locale = useState('locale', () => 'en')
  const t = (key) => messages[locale.value]?.[key] ?? messages.en?.[key] ?? key
  const toggleLocale = () => { locale.value = locale.value === 'en' ? 'fr' : 'en' }
  return { locale, t, toggleLocale }
}
